// `:joy:` and `:joy` both resolve; spaces in a label behave like underscores.
export const EMOJI_BY_NAME = new Map();
for (const emoji of ALL_EMOJIS) {
  const key = emoji.name.replace(/\s+/g, '_');
  if (!EMOJI_BY_NAME.has(key)) EMOJI_BY_NAME.set(key, emoji);
}
for (const [alias, char] of Object.entries(ALIASES)) {
  const emoji = EMOJI_BY_CHAR.get(char);
  if (emoji && !EMOJI_BY_NAME.has(alias)) EMOJI_BY_NAME.set(alias, emoji);
}

export function findEmojiByName(raw) {
  const key = String(raw || '').toLowerCase().replace(/\s+/g, '_');
  return key ? EMOJI_BY_NAME.get(key) || null : null;
}

export function searchEmojiByName(term, limit = 6) {
  const query = String(term || '').toLowerCase();
  if (!query) return [];
  const starts = [];
  const contains = [];
  const seen = new Set();
  for (const [name, emoji] of EMOJI_BY_NAME) {
    if (seen.has(emoji.char)) continue;
    if (name.startsWith(query)) {
      starts.push(emoji);
      seen.add(emoji.char);
    } else if (name.includes(query)) {
      contains.push(emoji);
      seen.add(emoji.char);
    }
    if (starts.length >= limit) break;
  }
  return [...starts, ...contains].slice(0, limit);
}
