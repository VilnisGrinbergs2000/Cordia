-- 015_safety.sql
-- Signals raised by src/safety.js: spam bursts, duplicate cross-channel posts,
-- invite spam, mass DMs, and predatory patterns in DMs from strangers.
CREATE TABLE IF NOT EXISTS safety_events (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  kind text NOT NULL,
  severity text NOT NULL DEFAULT 'medium',
  user_id bigint NOT NULL,
  target_id bigint,
  scope_type text,
  scope_id bigint,
  message_id bigint,
  detail jsonb NOT NULL DEFAULT '{}'::jsonb,
  created_at bigint NOT NULL,
  reviewed_at bigint,
  reviewed_by bigint
);

ALTER TABLE safety_events DROP CONSTRAINT IF EXISTS fk_safety_user;
ALTER TABLE safety_events ADD CONSTRAINT fk_safety_user
  FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE;
ALTER TABLE safety_events DROP CONSTRAINT IF EXISTS fk_safety_message;
ALTER TABLE safety_events ADD CONSTRAINT fk_safety_message
  FOREIGN KEY (message_id) REFERENCES messages(id) ON DELETE SET NULL;

CREATE INDEX IF NOT EXISTS idx_safety_created ON safety_events(created_at DESC);
CREATE INDEX IF NOT EXISTS idx_safety_user ON safety_events(user_id, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_safety_open ON safety_events(reviewed_at) WHERE reviewed_at IS NULL;
