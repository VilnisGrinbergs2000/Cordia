-- Per-server invite links. The permanent servers.invite_code stays the default
-- link; rows here add links that can expire, run out of uses, or be revoked.
CREATE TABLE IF NOT EXISTS server_invites (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  server_id bigint NOT NULL REFERENCES servers(id) ON DELETE CASCADE,
  code text NOT NULL,
  creator_id bigint REFERENCES users(id) ON DELETE SET NULL,
  max_uses integer NOT NULL DEFAULT 0,
  uses integer NOT NULL DEFAULT 0,
  expires_at bigint,
  revoked_at bigint,
  created_at bigint NOT NULL
);

CREATE UNIQUE INDEX IF NOT EXISTS server_invites_code_idx ON server_invites (code);
CREATE INDEX IF NOT EXISTS server_invites_server_idx
  ON server_invites (server_id, created_at DESC);
