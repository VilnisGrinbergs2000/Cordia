-- Applications are the developer surface: an app owns a bot user, a token, a
-- set of slash commands and a list of servers it has been installed into.
-- A bot is a normal users row with is_bot = 1, so every existing permission
-- check, membership row and message author works without a parallel model.
CREATE TABLE applications (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  owner_id bigint NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  name text NOT NULL,
  description text NOT NULL DEFAULT '',
  client_id text NOT NULL UNIQUE,
  token_hash text NOT NULL UNIQUE,
  token_hint text NOT NULL DEFAULT '',
  bot_user_id bigint NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  created_at bigint NOT NULL
);

CREATE INDEX idx_applications_owner ON applications(owner_id);
CREATE INDEX idx_applications_bot ON applications(bot_user_id);

CREATE TABLE application_commands (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  application_id bigint NOT NULL REFERENCES applications(id) ON DELETE CASCADE,
  name text NOT NULL,
  description text NOT NULL DEFAULT '',
  options jsonb NOT NULL DEFAULT '[]'::jsonb,
  created_at bigint NOT NULL,
  UNIQUE (application_id, name)
);

CREATE TABLE application_installs (
  application_id bigint NOT NULL REFERENCES applications(id) ON DELETE CASCADE,
  server_id bigint NOT NULL REFERENCES servers(id) ON DELETE CASCADE,
  installed_by bigint NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  created_at bigint NOT NULL,
  PRIMARY KEY (application_id, server_id)
);

-- One row per /command use. The token is the bot's permission to answer this
-- specific interaction: it is random, single-use and useless for anything else.
CREATE TABLE interactions (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  application_id bigint NOT NULL REFERENCES applications(id) ON DELETE CASCADE,
  server_id bigint NOT NULL REFERENCES servers(id) ON DELETE CASCADE,
  channel_id bigint NOT NULL REFERENCES channels(id) ON DELETE CASCADE,
  user_id bigint NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  command_name text NOT NULL,
  options jsonb NOT NULL DEFAULT '{}'::jsonb,
  token text NOT NULL UNIQUE,
  responded_at bigint,
  created_at bigint NOT NULL
);

CREATE INDEX idx_interactions_app ON interactions(application_id);

ALTER TABLE users ADD COLUMN IF NOT EXISTS is_bot bigint NOT NULL DEFAULT 0;
ALTER TABLE users ADD COLUMN IF NOT EXISTS bot_application_id bigint;
