-- Channel overrides and role categories.
--
-- channel_overrides holds per-channel allow/deny lists for a group or a single
-- member. Resolution is: server permissions, then group overrides from lowest
-- rank to highest, then the member override, with deny winning inside one row.
CREATE TABLE IF NOT EXISTS channel_overrides (
  channel_id bigint NOT NULL REFERENCES channels(id) ON DELETE CASCADE,
  target_type text NOT NULL,
  target_id bigint NOT NULL,
  allow text NOT NULL DEFAULT '[]',
  deny text NOT NULL DEFAULT '[]',
  updated_at bigint NOT NULL,
  PRIMARY KEY (channel_id, target_type, target_id)
);
CREATE INDEX IF NOT EXISTS idx_channel_overrides_channel ON channel_overrides(channel_id);

-- Categories are a display grouping for roles only; they carry no permissions.
CREATE TABLE IF NOT EXISTS group_categories (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  server_id bigint NOT NULL REFERENCES servers(id) ON DELETE CASCADE,
  name text NOT NULL,
  position bigint NOT NULL DEFAULT 0,
  created_at bigint NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_group_categories_server ON group_categories(server_id);

ALTER TABLE server_groups ADD COLUMN IF NOT EXISTS category_id bigint REFERENCES group_categories(id) ON DELETE SET NULL;
