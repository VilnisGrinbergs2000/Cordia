CREATE TABLE IF NOT EXISTS forum_tags (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  channel_id bigint NOT NULL REFERENCES channels(id) ON DELETE CASCADE,
  name text NOT NULL,
  color text NOT NULL DEFAULT '#6d5efc',
  position integer NOT NULL DEFAULT 0,
  created_at bigint NOT NULL
);

CREATE UNIQUE INDEX IF NOT EXISTS forum_tags_channel_name_idx
  ON forum_tags (channel_id, lower(name));

CREATE INDEX IF NOT EXISTS forum_tags_channel_position_idx
  ON forum_tags (channel_id, position, id);

CREATE TABLE IF NOT EXISTS thread_tags (
  thread_id bigint NOT NULL REFERENCES channels(id) ON DELETE CASCADE,
  tag_id bigint NOT NULL REFERENCES forum_tags(id) ON DELETE CASCADE,
  PRIMARY KEY (thread_id, tag_id)
);

CREATE INDEX IF NOT EXISTS thread_tags_tag_idx ON thread_tags (tag_id);
