-- Cordia Pro billing. Account-scoped: one subscription covers every device.
-- Nothing here is required for the free tier to keep working; the rows only
-- exist once someone checks out.

ALTER TABLE uploads ADD COLUMN IF NOT EXISTS bytes bigint NOT NULL DEFAULT 0;

CREATE INDEX IF NOT EXISTS uploads_user_id_idx ON uploads (user_id);

CREATE TABLE IF NOT EXISTS user_subscriptions (
  user_id bigint PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
  plan text NOT NULL,
  status text NOT NULL DEFAULT 'active',
  provider text NOT NULL DEFAULT 'mock',
  provider_customer_id text,
  provider_subscription_id text,
  current_period_end bigint,
  cancel_at_period_end boolean NOT NULL DEFAULT false,
  created_at bigint NOT NULL,
  updated_at bigint NOT NULL
);

CREATE TABLE IF NOT EXISTS billing_events (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id bigint REFERENCES users(id) ON DELETE SET NULL,
  kind text NOT NULL,
  provider_event_id text UNIQUE,
  amount_cents integer,
  currency text,
  payload jsonb,
  created_at bigint NOT NULL
);

CREATE INDEX IF NOT EXISTS billing_events_user_id_idx ON billing_events (user_id, created_at DESC);
