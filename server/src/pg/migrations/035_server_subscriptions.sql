-- Server subscriptions: any server can sell supporter tiers, with no partner
-- or affiliate gate. A tier can grant a role, so paying is the same thing as
-- joining a group; canceling takes the role back only if the subscription was
-- what granted it (granted_group_id), never a role assigned by hand.
CREATE TABLE IF NOT EXISTS server_tiers (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  server_id bigint NOT NULL REFERENCES servers(id) ON DELETE CASCADE,
  name text NOT NULL,
  description text NOT NULL DEFAULT '',
  price_cents bigint NOT NULL,
  interval text NOT NULL DEFAULT 'month',
  color text NOT NULL DEFAULT '#f59e0b',
  group_id bigint REFERENCES server_groups(id) ON DELETE SET NULL,
  position bigint NOT NULL DEFAULT 0,
  created_at bigint NOT NULL
);
CREATE UNIQUE INDEX IF NOT EXISTS idx_server_tiers_name ON server_tiers(server_id, lower(name));

CREATE TABLE IF NOT EXISTS server_subscriptions (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tier_id bigint NOT NULL REFERENCES server_tiers(id) ON DELETE CASCADE,
  server_id bigint NOT NULL REFERENCES servers(id) ON DELETE CASCADE,
  user_id bigint NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  status text NOT NULL DEFAULT 'active',
  provider text NOT NULL DEFAULT 'mock',
  granted_group_id bigint,
  started_at bigint NOT NULL,
  current_period_end bigint NOT NULL,
  cancel_at_period_end boolean NOT NULL DEFAULT false,
  updated_at bigint NOT NULL
);
CREATE UNIQUE INDEX IF NOT EXISTS idx_server_subs_unique ON server_subscriptions(tier_id, user_id);
CREATE INDEX IF NOT EXISTS idx_server_subs_user ON server_subscriptions(user_id);
CREATE INDEX IF NOT EXISTS idx_server_subs_server ON server_subscriptions(server_id);
