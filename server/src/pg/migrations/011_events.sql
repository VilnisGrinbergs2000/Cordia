-- Activation funnel. One row per event, written fire-and-forget so a failed
-- insert can never fail the request that produced it. user_id and server_id go
-- null when the subject is deleted; the counts still matter.
CREATE TABLE IF NOT EXISTS events (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  type text NOT NULL,
  user_id bigint REFERENCES users(id) ON DELETE SET NULL,
  server_id bigint REFERENCES servers(id) ON DELETE SET NULL,
  created_at bigint NOT NULL
);

CREATE INDEX IF NOT EXISTS events_type_created_idx ON events (type, created_at DESC);
CREATE INDEX IF NOT EXISTS events_user_idx ON events (user_id);
