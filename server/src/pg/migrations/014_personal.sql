-- 014_personal.sql
-- Three personal features that live outside the message table:
--   scheduled_messages  "send later" queue drained by src/scheduler.js
--   saved_messages      private bookmarks, independent of channel pins
--   user_notes          notes one user keeps about another, visible only to them

CREATE TABLE IF NOT EXISTS scheduled_messages (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id bigint NOT NULL,
  channel_id bigint NOT NULL,
  content text NOT NULL,
  send_at bigint NOT NULL,
  created_at bigint NOT NULL
);

ALTER TABLE scheduled_messages DROP CONSTRAINT IF EXISTS fk_scheduled_user;
ALTER TABLE scheduled_messages ADD CONSTRAINT fk_scheduled_user
  FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE;
ALTER TABLE scheduled_messages DROP CONSTRAINT IF EXISTS fk_scheduled_channel;
ALTER TABLE scheduled_messages ADD CONSTRAINT fk_scheduled_channel
  FOREIGN KEY (channel_id) REFERENCES channels(id) ON DELETE CASCADE;

CREATE INDEX IF NOT EXISTS idx_scheduled_due ON scheduled_messages(send_at);
CREATE INDEX IF NOT EXISTS idx_scheduled_user ON scheduled_messages(user_id, send_at);

CREATE TABLE IF NOT EXISTS saved_messages (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id bigint NOT NULL,
  message_id bigint NOT NULL,
  created_at bigint NOT NULL,
  UNIQUE (user_id, message_id)
);

ALTER TABLE saved_messages DROP CONSTRAINT IF EXISTS fk_saved_user;
ALTER TABLE saved_messages ADD CONSTRAINT fk_saved_user
  FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE;
ALTER TABLE saved_messages DROP CONSTRAINT IF EXISTS fk_saved_message;
ALTER TABLE saved_messages ADD CONSTRAINT fk_saved_message
  FOREIGN KEY (message_id) REFERENCES messages(id) ON DELETE CASCADE;

CREATE INDEX IF NOT EXISTS idx_saved_user ON saved_messages(user_id, created_at DESC);

CREATE TABLE IF NOT EXISTS user_notes (
  owner_id bigint NOT NULL,
  target_id bigint NOT NULL,
  note text NOT NULL DEFAULT '',
  updated_at bigint NOT NULL,
  PRIMARY KEY (owner_id, target_id)
);

ALTER TABLE user_notes DROP CONSTRAINT IF EXISTS fk_notes_owner;
ALTER TABLE user_notes ADD CONSTRAINT fk_notes_owner
  FOREIGN KEY (owner_id) REFERENCES users(id) ON DELETE CASCADE;
ALTER TABLE user_notes DROP CONSTRAINT IF EXISTS fk_notes_target;
ALTER TABLE user_notes ADD CONSTRAINT fk_notes_target
  FOREIGN KEY (target_id) REFERENCES users(id) ON DELETE CASCADE;
