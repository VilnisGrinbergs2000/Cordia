-- 001_baseline.sql
-- Postgres baseline translated from the SQLite snapshot tmp/parity/base.db (user_version=19).
-- Additive migration mirroring the current SQLite schema. FKs are hoisted to ALTER TABLE
-- so cyclic references (channels <-> messages) can be created in one pass.


CREATE TABLE users (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username text NOT NULL,
  email text NOT NULL,
  display_name text NOT NULL,
  password_hash text NOT NULL,
  role text NOT NULL DEFAULT 'user',
  banned bigint NOT NULL DEFAULT 0,
  avatar_color text NOT NULL DEFAULT '#6366f1',
  avatar_url text NOT NULL DEFAULT '',
  banner_color text NOT NULL DEFAULT '#0ea5e9',
  status_text text NOT NULL DEFAULT '',
  presence text NOT NULL DEFAULT 'online',
  bio text NOT NULL DEFAULT '',
  message_count bigint NOT NULL DEFAULT 0,
  voice_seconds bigint NOT NULL DEFAULT 0,
  created_at bigint NOT NULL,
  theme text NOT NULL DEFAULT 'iris',
  mode text NOT NULL DEFAULT 'ink',
  dm_privacy text NOT NULL DEFAULT 'friends',
  e2ee_public_key text NOT NULL DEFAULT '',
  e2ee_key_backup text NOT NULL DEFAULT '',
  e2ee_key_version bigint NOT NULL DEFAULT 0,
  e2ee_key_created_at bigint,
  e2ee_recovery_backup text NOT NULL DEFAULT '',
  e2ee_recovery_created_at bigint,
  e2ee_signing_public_key text NOT NULL DEFAULT '',
  e2ee_signed_prekey_id bigint,
  e2ee_signed_prekey_public text NOT NULL DEFAULT '',
  e2ee_signed_prekey_signature text NOT NULL DEFAULT '',
  e2ee_signed_prekey_created_at bigint,
  e2ee_recovery_verifier text NOT NULL DEFAULT '',
  token_version bigint NOT NULL DEFAULT 0
);

CREATE TABLE servers (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL,
  icon_color text NOT NULL DEFAULT '#6366f1',
  owner_id bigint NOT NULL,
  invite_code text NOT NULL UNIQUE,
  created_at bigint NOT NULL,
  description text NOT NULL DEFAULT '',
  icon_url text NOT NULL DEFAULT '',
  thread_archive_minutes bigint NOT NULL DEFAULT 1440,
  allow_external_emotes bigint NOT NULL DEFAULT 1,
  discoverable bigint NOT NULL DEFAULT 0,
  discover_category text NOT NULL DEFAULT 'Community',
  banner text NOT NULL DEFAULT '',
  welcome_enabled bigint NOT NULL DEFAULT 0,
  welcome_channel_id bigint,
  welcome_title text NOT NULL DEFAULT '',
  welcome_body text NOT NULL DEFAULT '',
  boost_count bigint NOT NULL DEFAULT 0,
  boost_level bigint NOT NULL DEFAULT 0
);

CREATE TABLE server_members (
  server_id bigint NOT NULL,
  user_id bigint NOT NULL,
  role text NOT NULL DEFAULT 'member',
  joined_at bigint NOT NULL,
  PRIMARY KEY (server_id, user_id)
);

CREATE TABLE channels (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  server_id bigint NOT NULL,
  name text NOT NULL,
  type text NOT NULL DEFAULT 'text',
  position bigint NOT NULL DEFAULT 0,
  created_at bigint NOT NULL,
  category_id bigint,
  parent_channel_id bigint,
  parent_message_id bigint,
  owner_id bigint,
  archived bigint NOT NULL DEFAULT 0,
  last_message_at bigint,
  message_count bigint NOT NULL DEFAULT 0,
  pinned bigint NOT NULL DEFAULT 0,
  guidelines text NOT NULL DEFAULT ''
);

CREATE TABLE dm_channels (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_a bigint NOT NULL,
  user_b bigint NOT NULL,
  created_at bigint NOT NULL,
  closed_by_a bigint NOT NULL DEFAULT 0,
  closed_by_b bigint NOT NULL DEFAULT 0,
  UNIQUE (user_a, user_b)
);

CREATE TABLE messages (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  channel_id bigint,
  dm_id bigint,
  user_id bigint NOT NULL,
  content text NOT NULL DEFAULT '',
  attachment_url text,
  attachment_name text,
  attachment_type text,
  created_at bigint NOT NULL,
  edited_at bigint,
  reply_to_id bigint,
  system_type text,
  e2ee bigint NOT NULL DEFAULT 0,
  e2ee_envelope text,
  thread_id bigint,
  voice_duration_ms bigint NOT NULL DEFAULT 0,
  forwarded_from bigint,
  forwarded_author text NOT NULL DEFAULT ''
);

CREATE TABLE reactions (
  message_id bigint NOT NULL,
  user_id bigint NOT NULL,
  emoji text NOT NULL,
  created_at bigint NOT NULL,
  PRIMARY KEY (message_id, user_id, emoji)
);

CREATE TABLE friendships (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  requester_id bigint NOT NULL,
  addressee_id bigint NOT NULL,
  status text NOT NULL DEFAULT 'pending',
