CREATE TABLE mentions (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  message_id bigint NOT NULL,
  user_id bigint NOT NULL,
  scope_type text NOT NULL,
  scope_id bigint NOT NULL,
  created_at bigint NOT NULL,
